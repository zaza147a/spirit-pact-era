import {readFileSync,appendFileSync} from 'node:fs';
import assert from 'node:assert/strict';
import {currentEndgamePlayer,WEAPON_VARIANTS} from '../tests/fixtures/current-210-endgame-player.mjs';
import {CARDS} from '../dist/catalog.js';
import {cardAllowedInSlot} from '../dist/card-effects.js';
const [job,mode]=process.argv.slice(2);
assert.ok(WEAPON_VARIANTS[job]&&['atk','matk','hp','clear'].includes(mode));
const first=JSON.parse(readFileSync(`docs/current-extreme-${job}-search-20261110.json`));
const second=JSON.parse(readFileSync(`docs/current-extreme-refine-${job}-${mode}-20261111.json`));
const baseWeapon=currentEndgamePlayer(job).gear.rightHand.id;
const pool=[first.best[mode],...second.results];
for(const id of WEAPON_VARIANTS[job].filter(x=>x!==baseWeapon))pool.push(...JSON.parse(readFileSync(`docs/current-extreme-weapon-${job}-${id.replaceAll('+','-')}-${mode}-20261111.json`)).results);
const baseline=pool.sort((a,b)=>b.highest-a.highest)[0];
const player=currentEndgamePlayer(job,{fusion:baseline.fusion,weaponChoice:baseline.weaponChoice,attributeProfile:baseline.attributeProfile,weaponId:baseline.weaponId});
const tasks=Object.entries(player.gear).filter(([,gear])=>!!gear).flatMap(([slot])=>Object.entries(CARDS).filter(([id,c])=>c.boss&&id!==player.sockets[slot]&&cardAllowedInSlot(c,slot,job)).map(([cardId])=>({slot,cardId})));
const results=tasks.map(({slot,cardId})=>{
 const file=`docs/current-extreme-card-${job}-${mode}-${slot}-${cardId}-20261111.json`;
 const report=JSON.parse(readFileSync(file));
 assert.equal(report.completed,1,file);
 assert.equal(report.results.length,1,file);
 const r=report.results[0];
 assert.equal(r.stopped,'first-failure',file);
 assert.equal(r.cardSlot,slot,file);
 assert.equal(r.cardId,cardId,file);
 assert.ok(Number.isInteger(r.highest),file);
 return r;
});
const winner=[baseline,...results].sort((a,b)=>b.highest-a.highest)[0];
const path='docs/handoff-12-jobs-loadout-2026-11-10.md';
const previous=readFileSync(path,'utf8');
const number=[...previous.matchAll(/^## 分段交接 (\d+)：/gm)].map(m=>+m[1]).reduce((a,b)=>Math.max(a,b),0)+1;
const change=winner===baseline?'單卡替換未突破基準':`最優替換 ${winner.cardSlot}/${winner.cardId}`;
appendFileSync(path,`\n## 分段交接 ${number}：${job} ${mode.toUpperCase()} 王卡單卡實戰搜尋\n\n- 完成 ${tasks.length} 項合法單卡替換，均使用正式極限試煉從第1層打至首次失敗，原始結果：\`docs/current-extreme-card-${job}-${mode}-*-20261111.json\`。\n- 三輪最佳固定配置基準 ${baseline.highest} 層；本輪最高 ${winner.highest} 層，${change}。\n- 僅單卡局部最優，不代表跨融合、武器、配點、多卡聯動、技能順序或多種子全局最優。未更動正式版或 main。\n- 通過結果完整性回歸後提交本段原始 JSON 及交接文件。\n`);
console.log(JSON.stringify({job,mode,number,completed:tasks.length,baseline:baseline.highest,highest:winner.highest}));
