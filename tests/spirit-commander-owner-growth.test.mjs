import assert from 'node:assert/strict';
import {commanderOwnerGrowth,commanderMainSkillMultiplier,commanderInheritedPetStats} from '../dist/commander-owner-growth.js';
const pet={atk:20000,matk:24000,def:1000,mdef:1100,aspd:185};
const owner={atk:12000,matk:9000,rawAtk:10000,rawMatk:8000,def:2000,mdef:1800};
const initial=commanderInheritedPetStats(pet,owner);
const boosted=commanderInheritedPetStats(pet,{...owner,atk:18000,matk:14500,def:2500,mdef:2200});
assert.ok(boosted.atk>initial.atk,'owner ATK increase must grow companion physical offense');
const invested=commanderInheritedPetStats(pet,{...owner,cardPower:80});
const equipped=commanderInheritedPetStats(pet,{...owner,gearPower:80});
assert.ok(equipped.atk>initial.atk&&equipped.matk>initial.matk,'owner enhanced equipment must strengthen both pets');
assert.ok(invested.atk>initial.atk&&invested.matk>initial.matk,'offensive character cards must strengthen both pets');
assert.ok(invested.atk<=pet.atk*1.36+1,'trained pet panel multiplier remains capped');
assert.ok(boosted.matk>initial.matk,'owner MATK increase must grow companion magic offense');
assert.ok(boosted.def>initial.def&&boosted.mdef>initial.mdef,'owner defensive progression must be inherited');
const durable=commanderInheritedPetStats({...pet,hp:10000,damageReduction:8},{...owner,hp:20000,damageReduction:30});
assert.equal(durable.hp,10200,'commander transfers 1% of owner maximum HP after survival rebalance');
assert.equal(durable.damageReduction,2.9,'commander receives a reduced pre-combat defense conversion');
assert.ok(commanderInheritedPetStats({...pet,hp:10000,damageReduction:35},{...owner,hp:20000,damageReduction:40}).damageReduction<=40,'pet reduction respects 40% cap');
assert.ok(invested.atk>=Math.round(pet.atk*1.26),'substantial owner card training must empower pets');
const freshOwner={...owner,atk:owner.rawAtk,matk:owner.rawMatk,cardPower:0,gearPower:0};
const fresh=commanderInheritedPetStats(pet,freshOwner);
assert.equal(fresh.atk,Math.round(pet.atk*.91),'untrained owner must have reduced free pet offense');
const fullyTrained=commanderInheritedPetStats(pet,{...owner,atk:owner.rawAtk*3,matk:owner.rawMatk*3,cardPower:200,gearPower:200});
assert.equal(fullyTrained.atk,Math.round(pet.atk*(.91+.36*1.23)),'fully trained owner retains bounded growth');
assert.equal(commanderMainSkillMultiplier({atk:0,matk:0},pet,'attack-magic'),1,'zero owner offense grants no main skill bonus');
assert.equal(commanderMainSkillMultiplier({atk:1000000,matk:1000000},pet,'attack-magic'),2.2,'main skill bonus is capped at +120%');
assert.ok(commanderMainSkillMultiplier(owner,pet,'attack-magic')>1,'owner offense raises main skill');
assert.ok(commanderMainSkillMultiplier({...owner,atk:0,def:600},pet,'attack-defense')>commanderMainSkillMultiplier({...owner,atk:0,def:200},pet,'attack-defense'),'defense fusion uses owner DEF');
assert.ok(invested.atk/fresh.atk>1.2,'cards must give meaningful progression compared with untrained baseline');
assert.equal(pet.atk,20000,'owner transfer must not mutate cached pet stats');
assert.equal(initial.aspd,pet.aspd,'unrelated pet stats must be preserved');
assert.ok(commanderOwnerGrowth(50000,10000)<=.24,'growth cap must hold');
assert.equal(commanderOwnerGrowth(10000,10000),0,'no extra multiplier at owner raw stat baseline');
assert.ok(commanderOwnerGrowth(15000,10000)>commanderOwnerGrowth(12000,10000));
console.log('PASS: commander owner-led pet growth monotonicity, soft cap and cache purity');
