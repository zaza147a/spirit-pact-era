import assert from 'node:assert/strict';
import {spiritItemInvestment,spiritCultivationProgress,spiritCultivationMultiplier} from '../dist/spirit-cultivation.js';
import {commanderInheritedPetStats} from '../dist/commander-owner-growth.js';
const gear=(rarity='common',enhancement=null,level=200)=>({level,rarity,enhancement});
const player=(item,sigil=0)=>({gear:Object.fromEntries(Array.from({length:10},(_,i)=>[i,item])),dawnSigil:sigil});
const pets=item=>Array.from({length:2},()=>({gear:{head:item,body:item,shoes:item}}));
const bare=spiritCultivationMultiplier(player(null),pets(null));
const early=spiritCultivationMultiplier(player(gear('rare',null,151)),pets(gear('rare',null,151)));
const mythic=spiritCultivationMultiplier(player(gear('mythic')),pets(gear('mythic')));
const full=spiritCultivationMultiplier(player(gear('mythic','SSS'),8),pets(gear('mythic','SSS')));
assert.equal(bare,.35);
assert.ok(bare<early&&early<mythic&&mythic<full,'growth must increase from weak to 200 mythic to SSS sigil 8');
assert.equal(full,1,'full level 200 mythic SSS and sigil 8 restores full strength');
assert.ok(mythic>.5&&mythic<.7,'unenhanced mythic should start catching up');
assert.ok(spiritCultivationProgress(player(gear('mythic','SSS'),8),pets(null))<1,'pet equipment is mandatory for full growth');
assert.ok(spiritCultivationProgress(player(null,8),pets(gear('mythic','SSS')))<1,'owner equipment is mandatory for full growth');
assert.equal(spiritItemInvestment(null),0);
const base={atk:5000,matk:6000,def:1000,mdef:1000};
const owner={atk:10000,matk:11000,rawAtk:9000,rawMatk:10000,cardPower:40,gearPower:30};
const weakPet=commanderInheritedPetStats(base,{...owner,cultivation:bare});
const mythicPet=commanderInheritedPetStats(base,{...owner,cultivation:mythic});
const strongPet=commanderInheritedPetStats(base,{...owner,cultivation:full});
assert.ok(weakPet.atk<mythicPet.atk&&mythicPet.atk<strongPet.atk);
assert.ok(weakPet.matk<mythicPet.matk&&mythicPet.matk<strongPet.matk);
console.log(JSON.stringify({complete:true,stages:{bare,early,mythic,full},claim:'Both jobs need owner and companion equipment plus max sigil for full strength'}));
